#!/usr/bin/env node

/**
 * Refresh the bundled IANA top level domain list.
 *
 * Fetches the root zone list at
 *   https://data.iana.org/TLD/tlds-alpha-by-domain.txt
 * and regenerates src/data/tlds.ts as one newline separated string of
 * lowercase labels (punycode `xn--` labels included, so IDN domains
 * validate once converted). The core turns the string into a Set at load
 * time.
 *
 * Run by hand, or via the weekly workflow
 * .github/workflows/update-lists.yml, which opens a pull request when
 * the list changed.
 *
 * Usage:
 *   node scripts/update-tlds.mjs
 *
 * Exits 0 on success, whether or not the file changed. Exits non zero on
 * a hard failure (network error, malformed answer, a suspiciously short
 * list), and then leaves the file as it is.
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { bold, cyan, green, red, yellow } from 'barva'

/** Where IANA publishes the list. */
const SOURCE_URL = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt'

/** The generated module. */
const OUTPUT_PATH = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'data',
  'tlds.ts'
)

/** Fewer entries than this means the download is broken. */
const MIN_ENTRIES = 1000

/** Labels any sane copy of the list has. */
const SANITY_TLDS = ['com', 'net', 'org', 'nl', 'de', 'uk', 'xn--p1ai']

/**
 * Fetch the IANA list.
 * @returns {Promise<string>} The raw file
 */
async function fetchTlds() {
  console.log(cyan`Fetching ${SOURCE_URL}`)
  const response = await fetch(SOURCE_URL)
  if (!response.ok) {
    throw new Error(
      `IANA answered HTTP ${response.status} ${response.statusText}`
    )
  }
  return response.text()
}

/**
 * Parse the IANA file: one uppercase label per line, a `#` header.
 * @param {string} raw - The file
 * @returns {string[]} Sorted lowercase labels
 */
function parseTlds(raw) {
  const tlds = new Set()
  for (const line of raw.split(/\r?\n/)) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) {
      continue
    }
    if (!/^[A-Za-z0-9-]+$/.test(trimmed)) {
      throw new Error(`Unexpected line in the IANA file: "${trimmed}"`)
    }
    tlds.add(trimmed.toLowerCase())
  }
  if (tlds.size < MIN_ENTRIES) {
    throw new Error(
      `Suspiciously short TLD list (${tlds.size} entries), ` +
        'refusing to overwrite.'
    )
  }
  for (const must of SANITY_TLDS) {
    if (!tlds.has(must)) {
      throw new Error(`The TLD list misses ${must}, refusing to overwrite.`)
    }
  }
  return [...tlds].sort()
}

/**
 * The `# Version ...` line of the IANA file.
 * @param {string} raw - The file
 * @returns {string} The version line, for the generated header
 */
function versionOf(raw) {
  const line = raw.split(/\r?\n/).find((l) => l.startsWith('# Version'))
  return line ? line.replace(/^#\s*/, 'IANA ') : 'IANA (no version header)'
}

/**
 * Render the module.
 * @param {string[]} tlds - Sorted labels
 * @param {string} version - The IANA version line
 * @returns {string} The module source
 */
function renderModule(tlds, version) {
  return `/**
 * IANA top level domain list.
 *
 * Generated by scripts/update-tlds.mjs, do not edit by hand. Refresh it
 * by running the script, or let the weekly workflow
 * .github/workflows/update-lists.yml open a pull request.
 *
 * Source: ${SOURCE_URL}
 * ${version}
 * Entry count: ${tlds.length}
 */

/** One lowercase label per line, punycode labels included. */
export const IANA_TLD_LIST: string = \`
${tlds.join('\n')}
\`
`
}

/**
 * The list part of a generated module, without the dated header.
 * @param {string | null} source - A module source
 * @returns {string | null} The labels
 */
function listOf(source) {
  return source?.split('`')[1] ?? null
}

/**
 * Fetch, parse and write the module when the list changed.
 */
async function main() {
  const raw = await fetchTlds()
  const tlds = parseTlds(raw)
  const version = versionOf(raw)
  console.log(green`Parsed ${String(tlds.length)} TLDs (${version})`)

  const next = renderModule(tlds, version)
  const previous = fs.existsSync(OUTPUT_PATH)
    ? fs.readFileSync(OUTPUT_PATH, 'utf8')
    : null
  if (listOf(previous) === listOf(next)) {
    console.log(yellow`No changes, ${OUTPUT_PATH} is current`)
    return
  }
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true })
  fs.writeFileSync(OUTPUT_PATH, next)
  console.log(green.bold`Wrote ${OUTPUT_PATH}`)
}

main().catch((error) => {
  console.error(red.bold`Failed to update the TLD list: ${error.message}`)
  console.error(bold`The existing file is left as it is.`)
  process.exitCode = 1
})
